def norm(s):
    return unicodedata.normalize("NFKC", s or "").strip()


def sub_of(name, extra=""):
    """店名（と、取り扱う食品などの手がかり）から分類の番号を返す。わからなければ 13-1（その他）"""
    for s in (norm(name), norm(extra)):
        if not s:
            continue
        for k, rx in SUBS:
            if rx.search(s):
                return k
    return "13-1"


def osm_sub(tags):
    name = tags.get("name:ja") or tags.get("name") or ""
    k = sub_of(name)
    if k != "13-1":
        return k
    for c in re.split(r"[;,]", tags.get("cuisine", "")):
        c = c.strip().lower()
        if c in OSM_CUISINE:
            return OSM_CUISINE[c]
    return OSM_AMENITY.get(tags.get("amenity", ""), "10-2" if tags.get("amenity") == "restaurant" else "13-1")
